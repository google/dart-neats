import 'dart:io';

import 'package:path/path.dart' as p;

/// Embeds `lib/src/syntax/dart.syntax` into `lib/src/syntax/dart_syntax.g.dart`.
void main() {
  final syntaxPath = p.join('lib', 'src', 'syntax', 'dart.syntax');
  final outputPath = p.join('lib', 'src', 'syntax', 'dart_syntax.g.dart');
  final syntax = File(syntaxPath).readAsStringSync().replaceAll('\r\n', '\n');
  if (syntax.contains("'''")) {
    throw StateError('$syntaxPath must not contain triple single quotes.');
  }
  File(outputPath).writeAsStringSync(
    '// GENERATED CODE - DO NOT MODIFY BY HAND\n'
    '// Generated by `dart run tool/embed_syntax.dart`.\n\n'
    "const dartSyntax = r'''\n"
    '$syntax'
    "''';\n",
  );
}
